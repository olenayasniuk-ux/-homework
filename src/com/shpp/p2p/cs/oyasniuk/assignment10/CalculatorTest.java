package com.shpp.p2p.cs.oyasniuk.assignment10;

import java.util.Arrays;

public class CalculatorTest {
    public static void main(String[] args) {
        System.out.println("=== ЗАПУСК АВТОМАТИЧНИХ ТЕСТІВ ===\n");

        // 1. Тест із прикладу задачі
        runTest(new String[]{"1+aB5*2", "aB5 = 2", "b=7"}); // Очікується: 5.0

        // 2. Тест на унарний мінус перед змінною та підстановку
        runTest(new String[]{"1+-a*2-a", "a=-2", "b=7"}); // Очікується: 7.0

        // 3. Тест на унарні мінуси та дробові ступені
        runTest(new String[]{"-a+3^8.9/---6+b*b", "a=-2.78", "b=-1.98"}); // Очікується: -2932.4913275076215

        // 4. Складний стрес-тест на ланцюжки знаків без змінних
        runTest(new String[]{"-28*-+-4^-2-----9/--71.5*-9"}); // Очікується: -0.6171328671328671  НЕ ПОРАХУВАВ

        // 5. Тест на базовий пріоритет операцій
        runTest(new String[]{"2+3*4-6/2"}); // Очікується: 11.0

        // 6. Тест на підстановку кількох змінних
        runTest(new String[]{"a+b*c", "a=1.5", "b=2", "c=3"}); // Очікується: 7.5

        // 7. Тест на пріоритет ступеня над множенням
        runTest(new String[]{"2^3*2+4"}); // Очікується: 20.0

        // 8. Тест на унарний мінус перед правою змінною
        runTest(new String[]{"x*-y+z", "x=4", "y=2", "z=-3"}); // Очікується: -11.0

        // 9. Тест на від'ємний ступінь
        runTest(new String[]{"a^b/4", "a=5", "b=-1"}); // Очікується: 0.05

        // 10. Складний тест на знаки, ступені та дроби
        runTest(new String[]{"2^-a*b-c/2", "a=-2", "b=0.5", "c=6"}); // Очікується: -1.0  НЕ ПОРАХУВАВ

        // 11. Тест на довгу формулу з повторенням змінних
        runTest(new String[]{"x*x+y*y-x*y*2", "x=3.5", "y=1.5"}); // Очікується: 4.0

        // 12. Тест на дробовий ступінь (корінь)
        runTest(new String[]{"4^0.5*-a/b", "a=-3", "b=1.5"}); // Очікується: 4.0

        // 13. Великий тест на багато дій та багато змінних
        runTest(new String[]{"a+b*c^2-d/e*f", "a=10", "b=2", "c=3", "d=8", "e=-4", "f=2.5"}); // Очікується: 33.0

        // 14. Складний тест на унарний мінус перед ступенем змінної
        runTest(new String[]{"-x^3/-y-z^2", "x=-2", "y=4", "z=1.5"}); // Очікується: -4.25

        // 15. Перевірка правоасоціативності ступеня (справа наліво)
        runTest(new String[]{"2^2^3"}); // Очікується: 256.0

        // 16. Перевірка пріоритету ступеня над унарним мінусом (-4^2 має бути як -(4^2))
        runTest(new String[]{"2*-4^2"}); // Очікується: -32.0
        runTest(new String[]{"-2^0.5"});         // Очікується: -1.4142135623730951

        runTest(new String[]{});                //Помилка: Не вказано математичний вираз
        runTest(new String[]{"0^-2"});            // Помилка: Не можна обчислити 0 ^ -2  НЕ ПОРАХУВАВ
        runTest(new String[]{"0^0"});                //Помилка: 0^0 невизначено
        runTest(new String[]{"2/0"});               //Помилка: На нуль ділити не можна!
        runTest(new String[]{"3/0.0"});                //Помилка: На нуль ділити не можна!
        runTest(new String[]{"4^0.5*-a/b", "a=", "b=1.5"});   //Помилка: Неправильно задані значення змінних
        runTest(new String[]{"4^0.5*-}/b", "a=", "b=1.5"});  //Помилка: У математичному виразі є недопустимі символи
        //runTest(new String[]{"4^0.a*-a/b", "a=7", "b=1.5"});
        runTest(new String[]{"4^0.5*-a/b", "b=1.5"}); //Помилка: Ви не ввели значення для всіх змінних

        // === ПОЗИТИВНІ ТЕСТИ ===

// 1. Базовий комплексний вираз із тригонометрією та вкладеними дужками
        runTest(new String[]{"1+(2+3-(4+5-sin(45*cos(a))))/b", "a=2", "b=7"}); // Очікується: 0.44609125107768577

// 2. Прості арифметичні операції з пріоритетом дужок
        runTest(new String[]{"(a+b)*3-4.5/0.5", "a=2", "b=7"}); // Очікується: 18.0

// 3. Піднесення до степеня та робота з дробами
        runTest(new String[]{"b^2+a^(-1)-3.14", "a=2", "b=7"}); // Очікується: 46.36

// 4. Логарифми (десятковий та двійковий)
        runTest(new String[]{"log10(100)*log2(b+1)", "a=2", "b=7"}); // Очікується: 6.0

// 5. Квадратний корінь та множення змінних
        runTest(new String[]{"sqrt(a*b+2)", "a=2", "b=7"}); // Очікується: 4.0

// 6. Комбінація взаємообернених функцій (тангенс та арктангенс)
        runTest(new String[]{"atan(tan(1))", "a=2", "b=7"}); // Очікується: 1.0

// 7. Глибока вкладеність функцій одна в одну
        runTest(new String[]{"sin(cos(sqrt(log10(10))))", "a=2", "b=7"}); // Очікується: 0.5143952585235492

// 8. Унарні мінуси перед змінними та виразами в дужках
        runTest(new String[]{"-a*-(b-3)", "a=2", "b=7"}); // Очікується: 8.0

// 9. Пріоритет оператора степеня над діленням
        runTest(new String[]{"a^3/0.25+b", "a=2", "b=7"}); // Очікується: 39.0

// 10. Множення на нульовий результат виразу
        runTest(new String[]{"(b-7)*sin(a)+cos(0)", "a=2", "b=7"}); // Очікується: 1.0


// === НЕГАТИВНІ ТЕСТИ (ОБРОБКА ПОМИЛОК) ===

// 11. Тест на ділення на нуль
        runTest(new String[]{"a/(b-7)", "a=2", "b=7"}); // Очікується помилка: Division by zero

// 12. Незбалансовані дужки (відсутня закриваюча дужка)
        runTest(new String[]{"1+(2*(a+b)", "a=2", "b=7"}); // Очікується помилка: Mismatched parentheses

// 13. Незбалансовані дужки (зайва закриваюча дужка)
        runTest(new String[]{"a+b)", "a=2", "b=7"}); // Очікується помилка: Unexpected closing parenthesis

// 14. Два бінарні оператори поспіль
        runTest(new String[]{"a+*b", "a=2", "b=7"}); // Очікується помилка: Invalid operator placement

// 15. Використання неоголошеної змінної
        runTest(new String[]{"a+b-x", "a=2", "b=7"}); // Очікується помилка: Unknown variable 'x'

// 16. Помилка в назві функції (описка)
        runTest(new String[]{"sinn(a)", "a=2", "b=7"}); // Очікується помилка: Unknown function 'sinn'

// 17. Відсутній аргумент всередині функції
        runTest(new String[]{"sqrt()", "a=2", "b=7"}); // Очікується помилка: Missing argument for function

// 18. Некоректний формат числа (дві крапки)
        runTest(new String[]{"a+2.5.3", "a=2", "b=7"}); // Очікується помилка: Invalid number format
                                                            // а видає англійською multiple points

// 19. Порожні дужки всередині виразу
        runTest(new String[]{"a+()", "a=2", "b=7"}); // Очікується помилка: Empty expression inside parentheses

// 20. Від'ємне значення під логарифмом
        runTest(new String[]{"log2(-a)", "a=2", "b=7"}); // Очікується помилка: Logarithm argument must be positive


    }

    private static void runTest(String[] testArgs) {
        System.out.println("👉 Аргументи: " + Arrays.toString(testArgs));
        // Просто викликаємо метод main твого калькулятора, передаючи масив
        Assignment10Part1.main(testArgs);
        System.out.println("--------------------------------------------------\n");
    }
}
